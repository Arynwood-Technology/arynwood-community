def load_backend(tmp: str):
    """Import the Grove the way a fresh install sees it, with a throwaway data folder."""
    for name in list(os.environ):
        if name.startswith(("GROVE_", "COMMUNITY_", "MAIL_")):
            del os.environ[name]
    os.environ["GROVE_DATA_DIR"] = tmp
    sys.path.insert(0, str(ROOT))
    import warnings
    warnings.filterwarnings("ignore", message="Duplicate Operation ID")
    from backend import api
    from backend.community import store
    store.initialize()
    con = sqlite3.connect(store.database_path())
    tables = {t: [c[1] for c in con.execute(f"PRAGMA table_info({t})")]
              for (t,) in con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")}
    con.close()
    return api.app, None, tables



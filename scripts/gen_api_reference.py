"""Write the Grove's API reference (docs/api/) from its own OpenAPI document and route handlers.

    .venv/bin/python scripts/gen_api_reference.py           rewrite docs/api/http/ and docs/api/openapi.json
    .venv/bin/python scripts/gen_api_reference.py --check   exit 1 if those files are out of date

docs/API.md, written by hand, is the overview these pages link to.

Every route the Grove serves is included. The Grove doesn't serve its OpenAPI document (openapi_url is off),
but FastAPI still builds it in-process, and it is the source for methods, paths, parameters, request bodies
and descriptions (the handlers' docstrings). It types no successful response (the handlers return plain
dicts), so outputs and errors are read from each handler's source: its return statements, what a stream
yields, the database columns behind a returned row, and the HTTPExceptions it, its dependencies and the
backend helpers it calls raise. Who may call each route is read the same way: the auth dependencies
(backend/community/auth.py) and the space membership checks the handler makes. Nothing is typed by hand.

No network, no CDN: the Grove is imported with a throwaway data folder.
"""
